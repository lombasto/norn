test('norn gen --check: clean after install; hand edit = drift (never overwritten); source edit = stale; missing; foreign file', () => {
  const sb = demoSandbox();
  assert.deepEqual(genCheck(sb.p, sb.machine, { meta: sb.meta, out: sb.out }).length, 17, 'before the first gen every target is missing');
  installProject(sb.p, sb.machine, { meta: sb.meta, out: sb.out });
  assert.deepEqual(genCheck(sb.p, sb.machine, { meta: sb.meta, out: sb.out }), []);
  const pack = `${sb.p.state}/packs/demo-runner.codex.md`;
  fs.appendFileSync(pack, 'hand edit\n');
  fs.appendFileSync(`${sb.meta}/projects/demo/skills/demo-tests/SKILL.md`, 'new line\n');
  fs.appendFileSync(`${sb.meta}/projects/demo/skills/demo-dispatch/SKILL.md`, 'new rule\n');
  fs.rmSync(`${sb.cfg}/agents/demo-planner.md`);
  const probs = genCheck(sb.p, sb.machine, { meta: sb.meta, out: sb.out });
  assert.ok(probs.some(x => x.startsWith(pack) && /drift \(edited after generation/.test(x)), probs.join('\n'));
  assert.ok(probs.some(x => x.startsWith(`${sb.cfg}/skills/demo-tests/SKILL.md`) && /stale/.test(x)));
  assert.ok(probs.some(x => x.startsWith(`${sb.cfg}/agents/demo-planner.md`) && /missing/.test(x)));
  // a stale include reaches the packs that include it
  assert.ok(probs.some(x => x.includes('controller.grok.md') && /stale/.test(x)), 'an included file change makes its packs stale');
  assert.ok(!probs.some(x => x.includes('demo-runner.grok.md')), 'a skill body change does not touch packs (they list path + trigger only)');
  const again = installProject(sb.p, sb.machine, { meta: sb.meta, out: sb.out });
  assert.ok(again.some(x => x.startsWith(pack) && /drift/.test(x)));
  assert.match(fs.readFileSync(pack, 'utf8'), /hand edit\n$/, 'the hand edit is kept');
  // a foreign (unmanaged, different) ~/.codex/AGENTS.md is reported and kept
  const sb2 = demoSandbox();
  fs.mkdirSync(`${sb2.home}/.codex`, { recursive: true }); fs.writeFileSync(`${sb2.home}/.codex/AGENTS.md`, 'mine\n');
  assert.ok(installProject(sb2.p, sb2.machine, { meta: sb2.meta, out: sb2.out }).some(x => /AGENTS\.md exists and is not managed by meta/.test(x)));
  assert.equal(fs.readFileSync(`${sb2.home}/.codex/AGENTS.md`, 'utf8'), 'mine\n');
  assert.ok(genCheck(sb2.p, sb2.machine, { meta: sb2.meta, out: sb2.out }).some(x => /AGENTS\.md exists and is not managed by meta/.test(x)));
});

test('an identical unmanaged target is adopted (today\'s hand-kept hook / AGENTS.md), not rewritten', () => {
  const sb = demoSandbox();
  installProject(sb.p, sb.machine, { meta: sb.meta, out: sb.out });
  const hook = `${sb.p.state}/resume-hook.json`, body = fs.readFileSync(hook);
  const sb2 = demoSandbox();
  const hook2 = `${sb2.p.state}/resume-hook.json`;
  fs.mkdirSync(path.dirname(hook2), { recursive: true });
  fs.writeFileSync(hook2, unplace(fs.readFileSync(path.join(GOLDEN, 'state', 'resume-hook.json'), 'utf8'), sb2.home));
  const before = fs.statSync(hook2).mtimeMs;
  assert.deepEqual(installProject(sb2.p, sb2.machine, { meta: sb2.meta, out: sb2.out }), []);
  assert.equal(fs.statSync(hook2).mtimeMs, before);
  const man = JSON.parse(fs.readFileSync(`${sb2.meta}/local/install-manifest.json`, 'utf8'));
  assert.deepEqual(man.entries.find(e => e.target === hook2).kind, 'hook');
  assert.deepEqual([...new Set(man.entries.map(e => e.kind))].sort(), ['agent', 'global', 'hook', 'pack', 'skill']);
  assert.ok(body.length > 100);
});

test('CLI: norn gen --check exit 0 when clean, 1 on drift; norn gen writes; temp HOME / config dir only', () => {
  const t = mkTmp('meta-gencli-');
  const root = path.join(t, 'meta'), home = path.join(t, 'home'), bin = path.join(t, 'bin'), cfg = path.join(t, 'cfg');
  for (const d of [root, home, bin, cfg]) fs.mkdirSync(d, { recursive: true });
  const W = process.platform === 'win32';
  fs.writeFileSync(path.join(bin, W ? 'git.exe' : 'git'), ''); fs.writeFileSync(path.join(bin, W ? 'claude.exe' : 'claude'), '');
  const env = { ...process.env, PATH: bin, HOME: home, USERPROFILE: home, CLAUDE_CONFIG_DIR: cfg, META_ROOT: root,
    LOCALAPPDATA: path.join(home, 'AppData', 'Local'), APPDATA: path.join(home, 'AppData', 'Roaming') };
  for (const k of ['META_STATE', 'META_PROJECT', 'META_ROLE', 'META_RUN_ID', 'NPM_CONFIG_PREFIX', 'npm_config_prefix']) delete env[k];
  const run = (...a) => { const r = spawnSync(process.execPath, [META_CLI, ...a], { env, encoding: 'utf8' }); return { code: r.status, out: r.stdout + r.stderr }; };
  const pd = path.join(root, 'projects', 'demo');
  fs.mkdirSync(path.join(pd, 'agents'), { recursive: true }); fs.mkdirSync(path.join(pd, 'roles'), { recursive: true });
  fs.writeFileSync(path.join(pd, 'agents', 'demo-impl.md'), '---\nname: demo-impl\n---\n# impl ${name}\n');
  fs.writeFileSync(path.join(pd, 'roles', 'controller.md'), '---\nname: controller\nresume: resume ${root:win}' + B + 'x\nresume_message: hi\n---\n# ctl\n');
  const f = path.join(pd, 'project.json');
  fs.writeFileSync(f, JSON.stringify({ schema: 1, name: 'demo', title: 'demo', root: '${home}/dev/demo',
    install: { agents: '${meta}/projects/demo/agents', roles: '${meta}/projects/demo/roles', resume_hook: '${state}/resume-hook.json' } }));
  assert.equal(run('setup', '--non-interactive', '--no-scheduler', '--project', f).code, 0);
  let r = run('gen', '--check');
  assert.equal(r.code, 0, r.out); assert.match(r.out, /gen --check: ok/);
  const hook = path.join(root, 'state', 'demo', 'resume-hook.json');
  assert.deepEqual(JSON.parse(fs.readFileSync(hook, 'utf8')),
    { hookSpecificOutput: { hookEventName: 'SessionStart', additionalContext: 'resume ' + fwd(home).split('/').join(B) + B + 'dev' + B + 'demo' + B + 'x' }, systemMessage: 'hi' });
  fs.appendFileSync(path.join(cfg, 'agents', 'demo-impl.md'), 'x');
  r = run('gen', '--check', '--project', f);
  assert.equal(r.code, 1); assert.match(r.out, /demo-impl\.md: drift \(edited after generation/);
  fs.appendFileSync(path.join(pd, 'roles', 'controller.md'), 'more\n');
  r = run('gen');
  assert.equal(r.code, 1, 'the drifted agent is refused'); assert.match(r.out, /demo-impl\.md was edited after install \(drift\): not overwritten/);
  assert.equal(run('gen', '--bogus').code, 2);
});

test('norn gen --check: a target hand-edited to exactly the generated bytes is not drift (norn gen re-records it, writes nothing)', () => {
  const sb = demoSandbox();
  installProject(sb.p, sb.machine, { meta: sb.meta, out: sb.out });
  const src = `${sb.meta}/projects/demo/skills/demo-tests/SKILL.md`, target = `${sb.cfg}/skills/demo-tests/SKILL.md`;
  fs.appendFileSync(src, 'new rule\n');
  fs.appendFileSync(target, 'new rule\n'); // the demo-dispatch case: the live copy was edited first, the source folded in after
  sb.lines.length = 0;
  assert.deepEqual(genCheck(sb.p, sb.machine, { meta: sb.meta, out: sb.out }), []);
  assert.ok(sb.lines.some(l => l.includes(target) && /same bytes/.test(l)), sb.lines.join('\n'));
  const before = fs.statSync(target).mtimeMs;
  assert.deepEqual(installProject(sb.p, sb.machine, { meta: sb.meta, out: sb.out }), []);
  assert.equal(fs.statSync(target).mtimeMs, before, 'not rewritten');
  sb.lines.length = 0;
  assert.deepEqual(genCheck(sb.p, sb.machine, { meta: sb.meta, out: sb.out }), []);
  assert.ok(!sb.lines.some(l => l.includes(target)), 're-recorded: no note any more');
});
