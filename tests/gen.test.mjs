// H3 rule generators (HARNESS-DESIGN sec. 5): installProject renders every harness target from projects/<p>/ - Claude agents /
// skills (today), the resume hook, packs per role x family, harness-global.md -> ~/.codex/AGENTS.md - and `norn gen --check` is
// the drift doctor for all of them. GOLDEN: tests/golden/targets/ = the demo fixture's Claude / Codex files with the home dir as
// <HOME> (forward), <HOME_WIN> (backslash) and <HOME_JWIN> (JSON-escaped backslash); the fixture tests/fixtures/projects/demo regenerates them byte-same.
import test from 'node:test';
import assert from 'node:assert/strict';
