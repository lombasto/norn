const REPO = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const META_CLI = path.join(REPO, 'engine', 'bin', 'norn.mjs');
const GOLDEN = path.join(REPO, 'tests', 'golden', 'targets');
const fwd = p => p.replace(/\\/g, '/');
const B = '\\';

function filesUnder(d) {
  return fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? filesUnder(path.join(d, e.name)) : [path.join(d, e.name)]);
}

// a temp home with <home>/dev/sdd-codex/projects/demo = a copy of tests/fixtures/projects/demo (the fixture project) (the live layout, temp root)
// grok packs come from the fixture's project.json (executors.grok, an enabled cli entry), not from a machine slot
function demoSandbox({ codex = true } = {}) {
  const t = mkTmp('meta-gen-');
  const home = fwd(path.join(t, 'hx')), meta = `${home}/dev/sdd-codex`, cfg = fwd(path.join(t, 'cfg'));
  // the fixture's own state/ stays out, tested relative to the fixture: every Norn worktree itself sits under <root>/state/...
  const src = path.join(REPO, 'tests', 'fixtures', 'projects', 'demo');
  fs.cpSync(src, `${meta}/projects/demo`, { recursive: true, filter: s => !/^state([\\/]|$)/.test(path.relative(src, s)) });
  fs.mkdirSync(cfg, { recursive: true });
  const machine = { schema: 1, home, claude: { exe: 'claude', config_dir: cfg }, codex: codex ? { exe: 'codex' } : null };
  const p = loadProject(`${meta}/projects/demo/project.json`, { home, meta });
  const lines = [], out = s => lines.push(s);
  return { t, home, meta, cfg, machine, p, out, lines };
}

const goldenTarget = (sb, rel) => {
  if (rel.startsWith('claude/')) return `${sb.cfg}/${rel.slice('claude/'.length)}`;
  if (rel === 'state/resume-hook.json') return `${sb.p.state}/resume-hook.json`;
  if (rel === 'codex/AGENTS.md') return `${sb.home}/.codex/AGENTS.md`;
  throw new Error('unmapped golden ' + rel);
};
const unplace = (s, home) => s.split('<HOME_JWIN>').join(home.split('/').join(B + B)).split('<HOME_WIN>').join(home.split('/').join(B)).split('<HOME>').join(home);

test('GOLDEN: the demo fixture regenerates its Claude agents / skills, the resume hook and ~/.codex/AGENTS.md byte-same', () => {
  const sb = demoSandbox();
  assert.deepEqual(installProject(sb.p, sb.machine, { meta: sb.meta, out: sb.out }), []);
  const rels = filesUnder(GOLDEN).map(f => fwd(path.relative(GOLDEN, f)));
  assert.equal(rels.length, 7);
  for (const rel of rels) {
    const want = unplace(fs.readFileSync(path.join(GOLDEN, rel), 'utf8'), sb.home);
    assert.equal(fs.readFileSync(goldenTarget(sb, rel), 'utf8'), want, rel);
  }
  // nothing else lands in the Claude config dir
  assert.deepEqual(filesUnder(sb.cfg).map(f => fwd(path.relative(sb.cfg, f))).sort(),
    rels.filter(r => r.startsWith('claude/')).map(r => r.slice(7)).sort());
});

test('packs: one per role x non-Claude family = body + includes + skills list + that adapter\'s headless snippet', () => {
  const sb = demoSandbox();
  installProject(sb.p, sb.machine, { meta: sb.meta, out: sb.out });
  const dir = `${sb.p.state}/packs`;
  const roles = ['checkin', 'controller', 'demo-implementer', 'demo-planner', 'demo-runner'];
  assert.deepEqual(fs.readdirSync(dir).sort(), roles.flatMap(r => [`${r}.codex.md`, `${r}.grok.md`]).sort());
  for (const fam of ['codex', 'grok']) {
    const impl = fs.readFileSync(`${dir}/demo-implementer.${fam}.md`, 'utf8');
    assert.match(impl, /^<!-- generated by norn gen from \$\{norn\}\/projects\/demo\/agents\/demo-implementer\.md for the \w+ harness/);
    assert.ok(!/^---$/m.test(impl.split('\n').slice(0, 3).join('\n')), 'frontmatter stripped');
    assert.ok(impl.includes(ADAPTERS[fam === 'codex' ? 'codex' : 'cli'].headless), 'headless snippet');   // grok = a cli executor
    assert.ok(impl.includes(`- demo-tests: read ${sb.cfg}/skills/demo-tests/SKILL.md when `), 'skills listed for a family without Claude skills');
    assert.ok(!/\$\{(meta|home|root|state|dev|name)(:win)?\}/.test(impl.split('\n').filter(l => !l.startsWith('<!-- ')).join('\n')), 'vars rendered');
    const ctl = fs.readFileSync(`${dir}/controller.${fam}.md`, 'utf8');
    assert.ok(ctl.includes(`<!-- include \${project_dir}/skills/demo-dispatch/SKILL.md -->`));
    assert.ok(ctl.includes(`${sb.meta}/projects/demo/../tools/codex-impl.sh`), 'included skill rendered');
    assert.ok(!ctl.includes('resume: DEMO'), 'role frontmatter not in the pack');
  }
});

