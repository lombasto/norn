// A guarded writer in its own process (tests/views-guard.test.mjs): writes <file> N times through writeGuarded, each text its own,
// and prints {"refused":n,"errors":[...]} - two of these at once are the fill / `norn views` / dashboard writers racing on one hash file.
import { writeGuarded } from '../../engine/lib/views.mjs';
const [hashFile, file, tag, n] = process.argv.slice(2);
let refused = 0; const errors = [];
for (let i = 0; i < Number(n); i++) {
  try { if (writeGuarded(hashFile, file, `<!-- GENERATED by norn -->\n${tag} ${i}\n`) === 'refused') refused++; } catch (e) { errors.push(`${e.code ?? ''} ${e.message}`); }
}
process.stdout.write(JSON.stringify({ refused, errors }));
