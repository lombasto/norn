// META-GTP-CV (GT-PARITY-PLAN 2.8; Gas Town buildCVSummary, internal/cmd/polecat_identity.go:710-783, and `gt costs`,
// internal/cmd/costs.go:48-93, cited): the worker track record per ROUTING KEY (executor, model, effort, agent) - the thing a
// check-in routes on; persona names add nothing (a name is per run, never a routing choice). Derived only: the run records,
// the deliverables (merged via git) and cost.mjs (usageOfRun + costRollup's calibration); no new records, no second accounting
// path - the window's runs and plan % must equal costRollup's for the same window (`check`).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { usageOfRun, costRollup } from './cost.mjs';
import { loadState } from './records.mjs';
import { loadDeliverables, deliverablesView, deliverableConfig } from './deliverables.mjs';
import { hashKey } from './views.mjs';
import { makeGit } from './dlvgit.mjs';

const DAY = 86400000;
export const CV_WINDOWS = [7, 30];
export const CV_BY = ['key', 'executor', 'model', 'agent', 'lane'];
export const CV_FILE = 'CV.md';
export const CV_HEADER = '<!-- GENERATED by norn from runs.jsonl + deliverables.jsonl + cost.mjs ("norn cv"; "norn views") - hand edits are refused -->';
const OUTS = ['done', 'stopped', 'handoff', 'limit', 'crash', 'killed', 'other'];
const REVERTED = /smoke red.*reverted/i;

const agentOf = r => r.data?.agent || r.data?.kind || '-';
const FIELDS = {
  executor: r => r.data?.executor || r.data?.kind || '-',
  model: r => r.data?.model || r.end?.model || '-',
  effort: r => r.data?.effort || r.end?.effort || '-',
  agent: agentOf,
  lane: r => r.data?.lane ?? '-',
};
const keyOf = (r, by) => (by === 'key' ? ['executor', 'model', 'effort', 'agent'] : [by]).reduce((k, f) => ({ ...k, [f]: FIELDS[f](r) }), {});
export const keyText = k => Object.values(k).join(' / ');
const endTs = r => { const h = (r.history || []).findLast(x => x.ev === 'end' || x.ev === 'kill' || x.ev === 'lost'); return h ? Date.parse(h.ts) : NaN; };
function outcomeOf(r) {
  if (r.state === 'killed') return 'killed';
  if (r.state !== 'exited') return 'other';
  const o = r.end?.outcome;
  return OUTS.includes(o) && o !== 'killed' ? o : 'other';
}
const ended = r => ['exited', 'killed', 'lost'].includes(r.state);
function quant(xs) {
  if (!xs.length) return null;
  const s = [...xs].sort((a, b) => a - b), n = s.length;
  return { median: n % 2 ? s[(n - 1) / 2] : (s[n / 2 - 1] + s[n / 2]) / 2, p90: s[Math.ceil(0.9 * n) - 1] };
}
const pct = (n, of) => (of ? (100 * n) / of : null);

/** The list price of one run in $: Claude = the recorded cost_usd; a typed executor = its price_usd_per_mtok x tokens; else null. */
function usdOf(r, u, executors) {
  if (typeof r.end?.cost_usd === 'number') return r.end.cost_usd;
  const price = executors?.[r.data?.executor]?.price_usd_per_mtok;
  return typeof price === 'number' && Number.isFinite(u.total) ? (u.total / 1e6) * price : null;
}

/**
 * One window. parts: [{ project, items (fold items; runs are kind 'run'), dlvs: dlvFacts(...) rows, executors (project.json executors) }];
 * o: { now, days, by (key | executor | model | agent | lane), cacheRPerPct, projectsDir, codexDir, cache, memo }.
 * -> { days, since, by, rows: [{ key, runs, ended, out %, wall_min, wall_budget, cacheR_per_done, merged72, reverted, usd_per_run,
 *    usd_runs, plan_pct, plan_pct_per_run }], totals: { runs, plan_pct }, rollup: { runs, plan_pct }, check: { runs, plan_pct } }
 */
export function cvWindow(parts, o = {}) {
  const now = o.now ?? Date.now(), days = o.days ?? 7, by = o.by ?? 'key', since = now - days * DAY;
  if (!CV_BY.includes(by)) throw new Error(`--by must be ${CV_BY.filter(b => b !== 'key').join(' | ')} (got ${by})`);
  const memo = o.memo || new Map(), cache = o.cache || new Map(), groups = new Map();
  const rollup = { runs: 0, plan_pct: null };
  const tot = { runs: 0, plan_pct: null };
  for (const p of parts) {
    const runs = (p.items || []).filter(i => i.kind === 'run');
    const ro = { now, days, cacheRPerPct: o.cacheRPerPct ?? null, projectsDir: o.projectsDir, codexDir: o.codexDir, cache, memo, project: p.project };
    const R = costRollup(runs, ro), mix = R.calib.mix, perPct = o.cacheRPerPct || null;
    rollup.runs += R.rows.reduce((a, x) => a + x.runs, 0);
    if (R.totals.claude.pct !== null) rollup.plan_pct = (rollup.plan_pct ?? 0) + R.totals.claude.pct;
    // the deliverable of each DONE run, and the reverted merges attributed to the lane's last DONE run before the MERGE run
    const dlvOf = new Map();
    for (const d of p.dlvs || []) for (const id of d.runs) dlvOf.set(id, d);
    const reverted = new Map();
    for (const m of runs) {
      if (m.data?.stage !== 'MERGE' || m.state !== 'exited' || m.end?.outcome !== 'stopped' || !REVERTED.test(m.end?.why || '')) continue;
      const t = Date.parse(m.created);
      const last = runs.filter(r => r !== m && r.data?.lane === m.data.lane && r.data?.stage !== 'MERGE' && r.end?.outcome === 'done' && endTs(r) <= t)
        .sort((a, b) => endTs(b) - endTs(a))[0];
      if (last) reverted.set(last.id, (reverted.get(last.id) || 0) + 1);
    }
    for (const r of runs) {
      const c = Date.parse(r.created);
      if (!(c >= since)) continue;
      const key = keyOf(r, by), k = JSON.stringify(key);
      let g = groups.get(k);
      if (!g) groups.set(k, g = { key, runs: 0, ended: 0, n: Object.fromEntries(OUTS.map(x => [x, 0])), walls: [], ratios: [], doneCr: 0, doneN: 0,
        m72: 0, mOf: 0, reverted: 0, usd: 0, usdN: 0, plan: null, planN: 0 });
      g.runs++; tot.runs++;
      const u = usageOfRun(r, ro);
      const usd = usdOf(r, u, p.executors);
      if (usd !== null) { g.usd += usd; g.usdN++; }
      if (u.family === 'claude' && u.tokens && perPct && mix !== null) {
        const x = (u.tokens.weighted * mix) / perPct;
        g.plan = (g.plan ?? 0) + x; g.planN++; tot.plan_pct = (tot.plan_pct ?? 0) + x;
      }
      g.reverted += reverted.get(r.id) || 0;
      if (!ended(r)) continue;
      g.ended++;
      const out = outcomeOf(r);
      g.n[out]++;
      const e = endTs(r), wall = (e - c) / 60000;
      if (Number.isFinite(wall)) { g.walls.push(wall); if (r.data?.budget_min > 0) g.ratios.push(wall / r.data.budget_min); }
      if (out === 'done') {
        if (u.tokens) { g.doneCr += u.tokens.cache_read; g.doneN++; }
        const d = dlvOf.get(r.id);
        if (d) { g.mOf++; if (d.merged_at && Date.parse(d.merged_at) - e <= 72 * 3600000) g.m72++; }
      }
    }
  }
  const rows = [...groups.values()].map(g => {
    const wq = quant(g.walls), rq = quant(g.ratios);
    return { key: g.key, runs: g.runs, ended: g.ended, out: Object.fromEntries(OUTS.map(x => [x, g.ended ? pct(g.n[x], g.ended) : null])),
      wall_min: wq, wall_budget: rq ? { ...rq, n: g.ratios.length } : null, cacheR_per_done: g.doneN ? g.doneCr / g.doneN : null,
      merged72: { n: g.m72, of: g.mOf, pct: pct(g.m72, g.mOf) }, reverted: g.reverted,
      usd_per_run: g.usdN ? g.usd / g.usdN : null, usd_runs: g.usdN, plan_pct: g.plan, plan_pct_per_run: g.planN ? g.plan / g.planN : null };
  }).sort((a, b) => b.runs - a.runs || keyText(a.key).localeCompare(keyText(b.key)));
  const close = (a, b) => (a === null || b === null ? a === b : Math.abs(a - b) <= 1e-9 * Math.max(1, Math.abs(b)));
  return { days, since: new Date(since).toISOString(), by, rows, totals: tot, rollup,
    check: { runs: tot.runs === rollup.runs, plan_pct: close(tot.plan_pct, rollup.plan_pct) } };
}

/** Both windows (7 d / 30 d), or the one o.days asks for. Ended runs are memoized once for both. */
export function cv(parts, o = {}) {
  const memo = o.memo || new Map(), cache = o.cache || new Map(), now = o.now ?? Date.now();
  const windows = (o.days ? [o.days] : CV_WINDOWS).map(days => cvWindow(parts, { ...o, now, days, memo, cache }));
  return { now: new Date(now).toISOString(), by: o.by ?? 'key', projects: parts.map(p => p.project), windows };
}

/**
 * The deliverable facts CV needs: { id, runs (the create run + every done event's run), merged_at (ISO) | null }. rows = the
 * deliverablesView rows (state merged / installed from git); merged_at = the commit time of the oldest first-parent commit of
 * main that descends from the tip (the merge, or the next commit after a fast-forward), else the tip's own time (tip = main).
 */
export function dlvFacts(dlvItems, rows, { main = 'main', git }) {
  const byId = new Map(rows.map(r => [r.id, r]));
  return dlvItems.map(it => {
    const runs = [...new Set([it.data?.run, ...(it.history || []).map(h => h.data?.run)].filter(Boolean))];
    const r = byId.get(it.id);
    let merged_at = null;
    const tip = r?.done_tip || r?.tip;
    if (r && (r.state === 'merged' || r.state === 'installed') && !r.superseded && tip) {
      const repo = r.repo || it.data?.repo;
      const lines = (git(repo, ['log', '--first-parent', '--ancestry-path', '--format=%cI', `${tip}..${main}`], { allowFail: true }) || '').trim().split(/\r?\n/).filter(Boolean);
      const t = lines.length ? lines.at(-1) : (git(repo, ['log', '-1', '--format=%cI', tip], { allowFail: true }) || '').trim();
      merged_at = Number.isFinite(Date.parse(t)) ? new Date(Date.parse(t)).toISOString() : null;
    }
    return { id: it.id, runs, merged_at };
  });
}

// ---------- text: `norn cv`, views/CV.md, the check-in pack ----------
const f0 = x => (x === null || x === undefined ? '-' : String(Math.round(x)));
const f2 = x => (x === null || x === undefined ? '-' : x.toFixed(2));
const kTok = x => (x === null ? '-' : x >= 1e6 ? (x / 1e6).toFixed(1) + 'M' : Math.round(x / 1e3) + 'k');
const COLS = 'runs | DONE % | STOP % | HO % | limit % | crash % | killed % | wall min med / p90 | wall/budget med / p90 | cacheR / DONE | merged 72 h | reverted | $ / run | plan % / run';
function line(r) {
  const o = r.out, w = r.wall_min, b = r.wall_budget;
  return `| ${keyText(r.key)} | ${r.runs} | ${f0(o.done)} | ${f0(o.stopped)} | ${f0(o.handoff)} | ${f0(o.limit)} | ${f0(o.crash)} | ${f0(o.killed)} | `
    + `${w ? `${f0(w.median)} / ${f0(w.p90)}` : '-'} | ${b ? `${f2(b.median)} / ${f2(b.p90)}` : '-'} | ${kTok(r.cacheR_per_done)} | `
    + `${r.merged72.of ? `${r.merged72.n}/${r.merged72.of}` : '-'} | ${r.reverted} | ${r.usd_per_run === null ? '-' : '$' + f2(r.usd_per_run)} | ${r.plan_pct_per_run === null ? '-' : f2(r.plan_pct_per_run)} |`;
}
const keyHead = by => (by === 'key' ? 'executor / model / effort / agent' : by);
export function renderWindow(w, level = '##') {
  const L = [`${level} ${w.days} d (runs started since ${w.since.slice(0, 16)}Z; by ${keyHead(w.by)})`, '',
    `| ${keyHead(w.by)} | ${COLS} |`, `|${'---|'.repeat(15)}`, ...w.rows.map(line), ''];
  L.push(`Totals: ${w.totals.runs} runs, plan % ${f2(w.totals.plan_pct)} - costRollup ${w.rollup.runs} runs, ${f2(w.rollup.plan_pct)} %`
    + `${w.check.runs && w.check.plan_pct ? ' (agree)' : ' DISAGREE: a second accounting path'}.`, '');
  return L.join('\n');
}
export function renderCv(c) {
  return [CV_HEADER, `# CV - worker track record (${c.projects.join(', ')}; ${c.now.slice(0, 16)}Z)`, '',
    'Outcome % over ended runs; wall = start -> end; merged 72 h = DONE runs whose deliverable reached main within 72 h of the run\'s end / '
    + 'DONE runs with a deliverable; reverted = MERGE runs STOPPED "smoke red ... reverted" on the lane\'s last DONE run; $ = list price '
    + '(Claude: recorded cost_usd; typed executors: price_usd_per_mtok; else -); plan % = cost.mjs %-of-week share.', '',
    ...c.windows.map(w => renderWindow(w))].join('\n');
}
/** The check-in pack's CV table: the top `top` keys by runs in the first (7 d) window, <= max bytes. */
export function cvPack(c, { top = 5, max = 600 } = {}) {
  const w = c.windows[0];
  const L = [`CV ${w.days} d (norn cv; key runs DONE/STOP/HO % wall/budget $/run plan%/run):`, 'key | runs | D/S/H % | w/b med | $/run | plan%/run'];
  for (const r of w.rows.slice(0, top)) {
    const o = r.out, k = keyText(r.key).replace(/claude-/g, '');
    L.push(`${k} | ${r.runs} | ${f0(o.done)}/${f0(o.stopped)}/${f0(o.handoff)} | ${r.wall_budget ? f2(r.wall_budget.median) : '-'} | `
      + `${r.usd_per_run === null ? '-' : f2(r.usd_per_run)} | ${r.plan_pct_per_run === null ? '-' : f2(r.plan_pct_per_run)}`);
  }
  let s = L.join('\n') + '\n';
  while (Buffer.byteLength(s) > max && L.length > 2) { L.pop(); s = L.join('\n') + '\n'; }
  return s;
}

// ---------- loading + the view file ----------
/** One project's CV input from its state dir: the run items, the deliverable facts (git: merged + landing time), the executors. */
export function cvPart(project = {}, { state = project.state, git = makeGit(), dlvs = true } = {}) {
  const items = Object.values(loadState(state).items);
  const dl = dlvs ? Object.values(loadDeliverables(state)) : [];
  const facts = dl.length ? dlvFacts(dl, deliverablesView({ stateDir: state, project, git }).rows, { main: deliverableConfig(project).main, git }) : [];
  return { project: project.name || path.basename(path.resolve(state)), items, dlvs: facts, executors: project.executors || {} };
}

const sha = s => crypto.createHash('sha256').update(s).digest('hex');
/** Write <stateDir>/views/CV.md (or file) like every view: a hand edit (text whose hash is not the last written) is refused.
 * Own hash file (views/cv-hashes.json): never races record()'s hashes.json. -> { written | unchanged | refused: [paths] } */
export function writeCvView(stateDir, text, file = null) {
  const vdir = path.join(stateDir, 'views'), p = path.resolve(file || path.join(vdir, CV_FILE)), hf = path.join(vdir, 'cv-hashes.json');
  fs.mkdirSync(vdir, { recursive: true });
  const hashes = fs.existsSync(hf) ? JSON.parse(fs.readFileSync(hf, 'utf8')) : {};
  const res = { written: [], unchanged: [], refused: [] };
  if (fs.existsSync(p)) {
    const cur = fs.readFileSync(p, 'utf8');
    if (cur === text) { res.unchanged.push(p); return res; }
    if (hashes[hashKey(p)] !== sha(cur)) { res.refused.push(p); return res; }
  }
  fs.mkdirSync(path.dirname(p), { recursive: true });
  const tmp = `${p}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text); fs.renameSync(tmp, p);
  hashes[hashKey(p)] = sha(text);
  fs.writeFileSync(`${hf}.${process.pid}.tmp`, JSON.stringify(hashes, null, 1) + '\n'); fs.renameSync(`${hf}.${process.pid}.tmp`, hf);
  res.written.push(p);
  return res;
}

/** The check-in pack's CV table of one project (7 d; no deliverables, so no git on the tick path); '' when no run started in 7 d or on error. */
export function checkinCv(project, { budget = {}, projectsDir, codexDir, now } = {}) {
  try {
    const c = cv([cvPart(project, { dlvs: false })], { days: 7, now, cacheRPerPct: budget.cacheR_per_pct ?? null, projectsDir, codexDir });
    return c.windows[0].rows.length ? cvPack(c) : '';
  } catch { return ''; }
}
