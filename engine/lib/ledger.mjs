// GTP-LEDGER (norn DIR-1 "work persists in git-backed hooks", DIR-83 "don't lose info and work"; GT-PARITY-PLAN sec. 2.2).
// ONE bare repo (machine.json ledger.dir, default <dev>/norn-ledger.git) whose work tree is the common parent of the state root and
// the reviews dir; a whitelist (WHITELIST below, mirrored into info/exclude) instead of `git add -A`; a private index inside the bare
// repo; one writer under a lock; branch machine/<hostname>. Blobs are written by this module from the very bytes it scanned for
// secrets (the scan and the commit can never see different content). The state repos' own .gitignore files and their nested .git
// dirs do not matter: the walk is ours, git only stores what we hand it. Node built-ins + the git binary only.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import zlib from 'node:zlib';
import { spawn, spawnSync } from 'node:child_process';
import { withLock, KINDS } from './records.mjs';

export const BIG_BYTES = 5 * 1024 * 1024;   // anything larger stays out (named in the commit message)
// the whitelist of a state/<project>/ dir: top-level text records + generated views; runs/*.json; views/** (GT-PARITY-PLAN 2.2). The record
// logs come from KINDS (RM-46 S1c, F4: a hand list had missed roadmap / mail / waivers / adopt / instructions / guard), so a new kind is backed up
const STATE_TOP = [...[...new Set(Object.values(KINDS).map(k => k.file))].map(f => new RegExp(`^${f}.*\\.jsonl$`)), /^notify.*\.jsonl$/, /\.md$/i, /^checkin-gate\.json$/];
const SKIP_DIRS = new Set(['logs', 'hb', '.git', 'local', 'node_modules']);
const SKIP_FILE = [/\.lock$/, /-cache\.json$/];
const SCRATCH = /^scratch/i;   // the kill-criterion re-plan (LEDGER-NOTES DECIDED): scratch copies were 1700 of 5277 files on 11-09
export const EXCLUDE = ['# GENERATED by norn ledger (engine/lib/ledger.mjs) - the walk applies these; never a secret in the ledger', 'logs/', 'hb/', 'local/', '.git/',
  'scratch*/', '*.lock', '*-cache.json', '# + any dir holding its own .git (a clone / worktree) + any file > 5 MB'];

const fwd = p => p.replace(/\\/g, '/');
const inside = (child, parent) => { const r = path.relative(parent, child); return r === '' || (!r.startsWith('..') && !path.isAbsolute(r)); };
function commonParent(a, b) {
  let p = path.dirname(a);
  while (!inside(b, p) && path.dirname(p) !== p) p = path.dirname(p);
  return p;
}
const host = () => (os.hostname() || 'machine').toLowerCase().replace(/[^a-z0-9._-]/g, '-');

/** machine.ledger -> the resolved config, or null (no `ledger` slot = the ledger is off; strictly additive, DIR-72) */
export function ledgerConfig(machine, { metaRoot, machineFile } = {}) {
  const L = machine?.ledger;
  if (!L || typeof L !== 'object') return null;
  const meta = path.resolve(metaRoot), dev = path.dirname(meta);
  const dir = path.resolve(L.dir || path.join(dev, 'norn-ledger.git'));
  const state_root = path.resolve(L.state_root || path.join(meta, 'state'));
  // reviews default: the install's sibling <install dir name>-reviews (the NOTES of its runs; no owner folder name in the engine)
  const reviews = path.resolve(L.reviews || path.join(dev, path.basename(meta) + '-reviews'));
  // META-GTP-FED: machine.json fed.host names the machine in the federation (two WSL distros may share a hostname)
  const name = /^[a-z0-9._-]+$/.test(machine?.fed?.host || '') ? machine.fed.host : host();
  return { dir, state_root, reviews, root: commonParent(state_root, reviews), branch: `machine/${name}`, remote: L.remote || null,
    machine_file: machineFile ? path.resolve(machineFile) : path.join(meta, 'local', 'machine.json') };
}

/** the secret values of machine.json (the ntfy topic, any token / key / secret / password field), read at run time; never printed.
 *  No machine.json = no secrets; one that does not parse throws: a blind scan would pass every file. */
export function secretsOf(file) {
  let s;
  try { s = fs.readFileSync(file, 'utf8'); } catch (e) { if (e.code === 'ENOENT') return []; throw e; }
  const m = JSON.parse(s.replace(/^﻿/, ''));
  const out = [];
  const walk = (o, k = '') => {
    if (typeof o === 'string') { if (/topic|token|key|secret|password|passwd|auth/i.test(k) && o.length >= 6) out.push(o); return; }
    if (o && typeof o === 'object') for (const [kk, v] of Object.entries(o)) walk(v, Array.isArray(o) ? k : kk);
  };
  walk(m);
  return [...new Set(out)];
}

/** the whitelist walk: { files: Map<rel, abs>, stat: Map<rel, "size:mtime">, big: [rel] } (rel = forward slashes, relative to the work tree) */
export function ledgerFiles(cfg) {
  const files = new Map(), stat = new Map(), big = [];
  const take = abs => {
    let st; try { st = fs.statSync(abs); } catch { return; }
    if (!st.isFile()) return;
    const rel = fwd(path.relative(cfg.root, abs));
    if (st.size > BIG_BYTES) big.push(rel); else { files.set(rel, abs); stat.set(rel, `${st.size}:${st.mtimeMs}`); }
  };
  const ls = d => { try { return fs.readdirSync(d, { withFileTypes: true }); } catch { return []; } };
  // below a walk root: a scratch* dir (disposable by name) and a nested clone / worktree (a `.git` entry: it has its own history) stay out
  const deep = (d, top = true) => {
    const es = ls(d);
    if (!top && es.some(e => e.name === '.git')) return;
    for (const e of es) {
      const f = path.join(d, e.name);
      if (e.isDirectory()) { if (!SKIP_DIRS.has(e.name) && !SCRATCH.test(e.name)) deep(f, false); } else if (!SKIP_FILE.some(r => r.test(e.name))) take(f);
    }
  };
  for (const p of ls(cfg.state_root)) {
    if (!p.isDirectory() || SKIP_DIRS.has(p.name)) continue;
    const pd = path.join(cfg.state_root, p.name);
    for (const e of ls(pd)) {
      const f = path.join(pd, e.name);
      if (e.isFile() && STATE_TOP.some(r => r.test(e.name)) && !SKIP_FILE.some(r => r.test(e.name))) take(f);
      else if (e.isDirectory() && e.name === 'runs') { for (const r of ls(f)) if (r.isFile() && r.name.endsWith('.json')) take(path.join(f, r.name)); }
      else if (e.isDirectory() && e.name === 'views') deep(f);
    }
  }
  if (!inside(cfg.reviews, cfg.state_root) && !inside(cfg.state_root, cfg.reviews)) deep(cfg.reviews);
  big.sort();
  return { files, big, stat };
}

function gitEnv(cfg, index) {
  const env = { ...process.env, GIT_DIR: cfg.dir, GIT_WORK_TREE: cfg.root, GIT_INDEX_FILE: index || path.join(cfg.dir, 'ledger-index'), GIT_TERMINAL_PROMPT: '0',
    GIT_AUTHOR_NAME: 'norn-ledger', GIT_AUTHOR_EMAIL: `ledger@${host()}`, GIT_COMMITTER_NAME: 'norn-ledger', GIT_COMMITTER_EMAIL: `ledger@${host()}` };
  for (const k of ['GIT_OBJECT_DIRECTORY', 'GIT_ALTERNATE_OBJECT_DIRECTORIES', 'GIT_NAMESPACE', 'GIT_CEILING_DIRECTORIES']) delete env[k];
  return env;
}
function git(cfg, args, { input, ok = [0], index, git: exe = 'git' } = {}) {
  const r = spawnSync(exe, args, { cwd: cfg.root, env: gitEnv(cfg, index), input, encoding: 'utf8', windowsHide: true, timeout: 120000, maxBuffer: 256 * 1024 * 1024 });
  if (r.error) throw r.error;
  if (!ok.includes(r.status)) throw new Error(`git ${args[0]} failed (${r.status}): ${(r.stderr || '').trim().split('\n').pop()}`);
  return { out: r.stdout, status: r.status };
}

/** create the bare repo once (idempotent); info/exclude documents the whitelist's exclusions */
export function ensureLedger(cfg, o = {}) {
  if (!fs.existsSync(path.join(cfg.dir, 'HEAD'))) {
    fs.mkdirSync(cfg.dir, { recursive: true });
    const r = spawnSync(o.git || 'git', ['init', '-q', '--bare', cfg.dir], { encoding: 'utf8', windowsHide: true, timeout: 120000 });
    if (r.status !== 0) throw new Error(`git init failed: ${(r.stderr || '').trim()}`);
    git(cfg, ['config', 'core.autocrlf', 'false'], o);
    git(cfg, ['config', 'gc.auto', '256'], o);
    git(cfg, ['symbolic-ref', 'HEAD', `refs/heads/${cfg.branch}`], o);
  }
  fs.mkdirSync(path.join(cfg.dir, 'info'), { recursive: true });
  const ex = path.join(cfg.dir, 'info', 'exclude'), want = EXCLUDE.join('\n') + '\n';
  if ((fs.existsSync(ex) ? fs.readFileSync(ex, 'utf8') : '') !== want) fs.writeFileSync(ex, want);
}

// a loose blob from the exact bytes we scanned (sha1 object format); sync.mjs publishes home/<id> through it too
export function writeBlob(cfg, buf) {
  const head = Buffer.from(`blob ${buf.length}\0`), full = Buffer.concat([head, buf]);
  const sha = crypto.createHash('sha1').update(full).digest('hex');
  const f = path.join(cfg.dir, 'objects', sha.slice(0, 2), sha.slice(2));
  if (!fs.existsSync(f)) {
    fs.mkdirSync(path.dirname(f), { recursive: true });
    const tmp = `${f}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, zlib.deflateSync(full));
    try { fs.renameSync(tmp, f); } catch (e) { try { fs.unlinkSync(tmp); } catch { /* gone */ } if (!fs.existsSync(f)) throw e; }
  }
  return sha;
}

const logTo = (cfg, s) => { try { fs.appendFileSync(path.join(cfg.dir, 'ledger.log'), `${new Date().toISOString()} ${s}\n`); } catch { /* no dir */ } };
// the branch head without a spawn: the loose ref, else packed-refs (gc may pack it)
function headOf(cfg) {
  const ref = `refs/heads/${cfg.branch}`;
  try { return fs.readFileSync(path.join(cfg.dir, ...ref.split('/')), 'utf8').trim() || null; } catch { /* packed or none */ }
  try { const l = fs.readFileSync(path.join(cfg.dir, 'packed-refs'), 'utf8').split('\n').find(x => x.endsWith(' ' + ref)); return l ? l.split(' ')[0] : null; } catch { return null; }
}
// <ledger>/ledger-manifest.json = { head, tree, files: { rel: "size:mtime" } } of the last commit: a no-op pass spawns no git at all
const manifestFile = cfg => path.join(cfg.dir, 'ledger-manifest.json');
function readManifest(cfg) {
  try { const m = JSON.parse(fs.readFileSync(manifestFile(cfg), 'utf8')); if (m && m.files && typeof m.files === 'object') return m; } catch { /* none / torn */ }
  return null;
}
function writeManifest(cfg, m) { const f = manifestFile(cfg), tmp = `${f}.${process.pid}.tmp`; fs.writeFileSync(tmp, JSON.stringify(m)); fs.renameSync(tmp, f); }

// what differs between the walk and the last commit: { changed, removed, files, stat, big, manifest (null = rebuild from the walk) }
function pending(cfg) {
  const { files, stat, big } = ledgerFiles(cfg);
  const head = headOf(cfg), m0 = readManifest(cfg), m = m0 && m0.head === head ? m0 : null;
  const old = m ? m.files : {}, bigSet = new Set(big);
  const changed = [...files.keys()].filter(f => old[f] !== stat.get(f)).sort();
  const removed = Object.keys(old).filter(f => !files.has(f) && !bigSet.has(f)).sort();
  return { changed, removed, files, stat, big, manifest: m, head };
}

/**
 * commit(reason): the whitelist into refs/heads/machine/<host> under the ledger lock. Returns { sha } | { noop: true } |
 * { refused: [file] } (a staged file holds a machine.json secret; nothing staged) | { error } (never throws: callers log it).
 * o: { git, lockTimeoutMs, push (false = no async push) }
 */
export function commitLedger(cfg, reason, o = {}) {
  const t0 = Date.now();
  try {
    ensureLedger(cfg, o);
    return withLock(path.join(cfg.dir, 'ledger.lock'), () => {
      const p = pending(cfg), parent = p.head;
      if (!p.changed.length && !p.removed.length && parent && p.manifest) return { noop: true, ms: Date.now() - t0 };
      const secrets = secretsOf(cfg.machine_file).map(s => Buffer.from(s));
      const bufs = new Map(), refused = [];
      for (const rel of p.changed) {
        let b; try { b = fs.readFileSync(p.files.get(rel)); } catch { continue; }   // vanished meanwhile: next pass
        if (secrets.some(s => b.includes(s))) refused.push(rel); else bufs.set(rel, b);
      }
      if (refused.length) { logTo(cfg, `commit refused - a machine.json secret value in: ${refused.join(', ')}`); return { refused, ms: Date.now() - t0 }; }
      const idx = path.join(cfg.dir, 'ledger-index');
      if (!p.manifest) { try { fs.unlinkSync(idx); } catch { /* none */ } }   // no / stale manifest: the index is rebuilt from the walk
      const lines = [...[...bufs].map(([rel, b]) => `100644 ${writeBlob(cfg, b)}\t${rel}`), ...p.removed.map(rel => `0 ${'0'.repeat(40)}\t${rel}`)];
      if (lines.length) git(cfg, ['update-index', '--add', '--remove', '-z', '--index-info'], { ...o, input: lines.join('\0') + '\0' });
      const tree = git(cfg, ['write-tree'], o).out.trim();
      const files = {};
      for (const [rel] of p.files) if (bufs.has(rel) || (p.manifest?.files[rel] === p.stat.get(rel))) files[rel] = p.stat.get(rel);
      const prevTree = p.manifest?.tree || (parent ? git(cfg, ['rev-parse', `${parent}^{tree}`], o).out.trim() : null);
      if (parent && prevTree === tree) { writeManifest(cfg, { head: parent, tree, files }); return { noop: true, ms: Date.now() - t0 }; }
      const msg = `ledger: ${reason || 'pass'}\n\n${bufs.size} changed, ${p.removed.length} removed` + (p.big.length ? `\nskipped > 5 MB: ${p.big.join(', ')}` : '') + '\n';
      const sha = git(cfg, ['commit-tree', tree, ...(parent ? ['-p', parent] : []), '-F', '-'], { ...o, input: msg }).out.trim();
      git(cfg, ['update-ref', `refs/heads/${cfg.branch}`, sha, ...(parent ? [parent] : [])], o);
      writeManifest(cfg, { head: sha, tree, files });
      if (cfg.remote && o.push !== false) pushAsync(cfg, o);
      if (o.gc !== false) detached(cfg, ['gc', '--auto', '--quiet'], 'gc.log', o);   // plumbing commits never auto-gc: loose blobs of the jsonl files pack into deltas
      return { sha, changed: bufs.size, removed: p.removed.length, big: p.big, ms: Date.now() - t0 };
    }, { staleMs: 120000, timeoutMs: o.lockTimeoutMs ?? 20000 });
  } catch (e) {
    logTo(cfg, `commit failed: ${e.message}`);
    return { error: e.message, ms: Date.now() - t0 };
  }
}

// never blocks: a detached git (push / gc); its output goes to <ledger>/<log>
function detached(cfg, args, log, o = {}) {
  try {
    const fd = fs.openSync(path.join(cfg.dir, log), 'a');
    spawn(o.git || 'git', args, { cwd: cfg.dir, env: gitEnv(cfg), detached: true, stdio: ['ignore', fd, fd], windowsHide: true }).unref();
    fs.closeSync(fd);
  } catch (e) { logTo(cfg, `${args[0]} not started: ${e.message}`); }
}
// `git push <remote> machine/<host>` (ledger.remote set); outcome in <ledger>/push.log
export function pushAsync(cfg, o = {}) { const ref = `refs/heads/${cfg.branch}`; detached(cfg, ['push', '-q', cfg.remote, `${ref}:${ref}`], 'push.log', o); }

/** a ledger step for the tick / run end: never throws, returns a one-line note or null (no-op / off) */
export function ledgerStep(cfg, reason, o = {}) {
  if (!cfg) return null;
  const r = commitLedger(cfg, reason, o);
  if (r.error) return `ledger: failed: ${r.error}`;
  if (r.refused) return `ledger: commit refused (secret value in ${r.refused.join(', ')})`;
  if (r.noop) return null;
  return `ledger: ${r.sha.slice(0, 10)} (${r.changed} changed, ${r.removed} removed, ${r.ms} ms)`;
}

export function ledgerStatus(cfg) {
  const s = { dir: fwd(cfg.dir), root: fwd(cfg.root), branch: cfg.branch, remote: cfg.remote ? 'set' : null, exists: fs.existsSync(path.join(cfg.dir, 'HEAD')) };
  if (!s.exists) return s;
  const head = headOf(cfg);
  s.head = head;
  if (head) { const [date, ...subj] = git(cfg, ['log', '-1', '--format=%cI %s', head]).out.trim().split(' '); s.date = date; s.subject = subj.join(' '); }
  const p = pending(cfg);
  s.tracked = git(cfg, ['ls-files', '-z']).out.split('\0').filter(Boolean).length;
  s.pending = p.changed.length + p.removed.length;
  s.big = p.big;
  return s;
}

export function ledgerLog(cfg, n = 20) {
  if (!headOf(cfg)) return [];
  return git(cfg, ['log', `-n${Number(n) || 20}`, '--format=%h %cI %s', `refs/heads/${cfg.branch}`]).out.split('\n').filter(Boolean);
}

/** check out <at> into a scratch dir; refuses a live path (inside the state root / reviews dir / ledger, or the work tree root or above) */
export function ledgerRestore(cfg, { at, to }) {
  if (!at || !to) throw new Error('restore needs --at <sha> and --to <scratch dir>');
  const dest = path.resolve(to);
  // the work tree root itself (or above it) is live; a scratch dir beside the state root / reviews dir under it is not
  for (const live of [cfg.state_root, cfg.reviews, cfg.dir, cfg.root])
    if ((live !== cfg.root && inside(dest, live)) || inside(live, dest)) throw new Error(`refused: ${fwd(dest)} is a live path (${fwd(live)}) - restore into a scratch dir`);
  if (fs.existsSync(dest) && fs.readdirSync(dest).length) throw new Error(`refused: ${fwd(dest)} is not empty`);
  const sha = git(cfg, ['rev-parse', '--verify', `${at}^{commit}`]).out.trim();
  const index = path.join(os.tmpdir(), `ledger-restore-${process.pid}-${Date.now()}.index`);
  fs.mkdirSync(dest, { recursive: true });
  try {
    git(cfg, ['read-tree', sha], { index });
    git(cfg, ['checkout-index', '-a', '-f', `--prefix=${fwd(dest)}/`], { index });
  } finally { try { fs.unlinkSync(index); } catch { /* gone */ } }
  return { sha, to: fwd(dest) };
}
