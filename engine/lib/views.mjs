export const HEADER = '<!-- GENERATED by norn from records.jsonl - edit with the dashboard or "norn rec"; hand edits are refused -->';
export const VIEW_FILES = { questions: 'OWNER-QUESTIONS.md', decisions: 'DECISIONS-LOG.md', directives: 'DIRECTIVES.md', queue: 'META-QUEUE.md' };

const num = id => Number(id.replace(/^\D+-/, ''));
const ofKind = (st, kind) => Object.values(st.items).filter(i => i.kind === kind).sort((a, b) => num(a.id) - num(b.id));
const cell = v => (v === undefined || v === null ? '' : Array.isArray(v) ? v.join(', ') : String(v)).replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');
const who = it => (it.by === 'migration' && it.data?.legacy_by ? `${it.data.legacy_by} (migrated)` : it.by) +(it.run ? ` (${it.run})` : '');

function closedLine(q) {
  if (q.state === 'applied') return `applied ${q.apply.refs.join(', ')} (${q.updated})`;
  if (q.state === 'superseded') return `superseded by ${q.supersede.by}: ${q.supersede.why} (${q.updated})`;
  if (q.state === 'withdrawn') return `withdrawn${q.withdraw.why ? ': ' + q.withdraw.why : ''} (${q.updated})`;
  return q.state;
}

function questionBlock(q) {
  const d = q.data;
  const meta = [`lane ${d.lane}`, d.class ? `class ${d.class}` : null, d.blocks?.length ? `blocks ${d.blocks.join(', ')}` : null,
    `asked ${q.created} by ${who(q)}`, d.source ? `source ${d.source}` : null].filter(Boolean).join(' · ');
  const out = [`### ${q.id} · ${d.title}`, meta];
  if (d.body) out.push('', d.body);
  if (d.options?.length) { out.push('', 'Options:'); for (const o of d.options) out.push(`- **${o.key}** ${o.text}${o.cost ? ` (cost: ${o.cost})` : ''}`); }
  if (d.recommend) out.push('', `Recommended: **${d.recommend.key}** - ${d.recommend.why}`);
  if (q.state === 'answered') out.push('', `Answer (${q.answer.via}, ${q.history.findLast(h => h.ev === 'answer').ts}): ${q.answer.choice ? `**${q.answer.choice}** - ` : ''}"${q.answer.text}"`);
  return out.join('\n');
}

export function renderQuestions(st) {
  const qs = ofKind(st, 'question');
  const open = qs.filter(q => q.state === 'open'), answered = qs.filter(q => q.state === 'answered');
  const closed = qs.filter(q => !['open', 'answered'].includes(q.state));
  const out = [HEADER, '# Owner questions', '', `## Open (${open.length})`];
  for (const q of open) out.push('', questionBlock(q));
  out.push('', `## Answered, not applied (${answered.length})`);
  for (const q of answered) out.push('', questionBlock(q));
  out.push('', `## Closed (${closed.length})`, '');
  for (const q of closed) out.push(`- ${q.id} · ${q.data.title} - ${closedLine(q)}`);
  return out.join('\n') + '\n';
}

export function renderDecisions(st) {
  const out = [HEADER, '# Decisions log', '', '| id | state | date | lane | question | choice | why | cost | source | by | answers | notify |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|'];
  for (const d of ofKind(st, 'decision')) {
    const x = d.data;
    const state = d.state === 'superseded' ? `superseded by ${d.supersede.by}: ${d.supersede.why}`
      : d.state === 'overruled' ? `overruled: ${d.overrule.text}${d.overrule.rework_lane ? ` (rework ${d.overrule.rework_lane})` : ''}` : d.state;
    out.push('| ' + [d.id, state, d.created, x.lane, x.question, x.choice, x.why, x.cost, x.source, who(d), x.answers, x.notify ? 'FYI' : ''].map(cell).join(' | ') + ' |');
  }
  return out.join('\n') + '\n';
}

export function renderDirectives(st) {
  const ds = ofKind(st, 'directive');
  const line = d => {
    const x = d.data;
    const tags = [d.created, x.via, x.scope?.length ? `scope ${x.scope.join(', ')}` : null, x.expires_utc ? `expires ${x.expires_utc}` : null].filter(Boolean).join(', ');
    const end = d.state === 'superseded' ? ` - superseded${d.supersede.by ? ` by ${d.supersede.by}` : ''}: ${d.supersede.why}`
      : d.state === 'done' ? ` - done ${d.done.refs.join(', ')}` : d.state === 'revoked' ? ' - revoked' : '';
    return `- ${d.id} (${tags}): ${x.text.replace(/\r?\n/g, ' ')}${end}`;
  };
  const active = ds.filter(d => d.state === 'active'), closed = ds.filter(d => d.state !== 'active');
  return [HEADER, '# Active owner directives (add / revoke in the dashboard; full history: norn rec list --kind DIR)', '', `## Active (${active.length})`, '', ...active.map(line), '', `## Closed (${closed.length})`, '', ...closed.map(line)].join('\n') + '\n';
}

// NORN-WATCH S4: META-QUEUE.md as a generated view - running / queued (+ each after: condition, inputs) / the last 10 ends.
// evalAfter (after.mjs makeEval) evaluates the triggers; without it a condition shows `?`. No clock in the text: one state = one text.
// META-GTP-DAG piece 3: ready = the dry fill walk's rows (runs.mjs readiness); each queued row ends with its words (readyWords) and the
// rows follow the fill order. Without them (a caller with no walk) the order is FIFO and no words are printed.
export function renderQueue(st, { evalAfter = null, ready = null } = {}) {
  const runs = ofKind(st, 'run');
  const tag = r => [r.id, r.data.name, r.data.lane ? `lane ${r.data.lane}` : null, r.data.stage, r.data.executor, r.data.model !== r.data.executor && r.data.model].filter(Boolean).join(' ');   // the fake's model is 'fake': said once
  const running = runs.filter(r => r.state === 'running');
  const R = ready ? new Map(ready.map((r, i) => [r.id, { ...r, order: i }])) : null;
  const queued = runs.filter(r => r.state === 'queued').sort((a, b) => (R ? (R.get(a.id)?.order ?? 1e9) - (R.get(b.id)?.order ?? 1e9) : 0));
  const words = r => { const x = R?.get(r.id); return x ? '; ' + readyWords(x) : ''; };
  const pe = r => [r.data.priority, r.data.epic].filter(Boolean).join(' ');
  const ends = runs.filter(r => ['exited', 'lost', 'killed', 'withdrawn'].includes(r.state)).sort((a, b) => Date.parse(b.updated) - Date.parse(a.updated) || num(b.id) - num(a.id)).slice(0, 10);
  const trig = r => {
    const after = r.data.after || [];
    if (!after.length) return '';
    const word = c => (c.met ? 'met' : c.gone ? `GONE (${c.gone})` : 'unmet');
    const a = evalAfter ? evalAll(after, evalAfter).conds : after.map(c => ({ cond: `${c.kind}:${c.id}:${c.state}`, met: null }));
    return '; after ' + a.map(c => `${c.cond} ${c.met === null ? '?' : word(c)}`).join(', ');
  };
  const endWord = r => r.state === 'exited' ? `ended ${r.end?.outcome ?? '?'}` : r.state === 'withdrawn' ? `withdrawn${r.withdraw?.why ? ': ' + r.withdraw.why : ''}` : r.state;
  return [HEADER, '# Queue - running, queued (with the trigger that releases each), recent ends',
    '', '(Prose next actions live in the ledger + DEC records; queue a triggered run with `norn run ... --after <conds> --inputs DLV-n`.)',
    '', `## Running (${running.length})`, '', ...running.map(r => `- ${tag(r)} since ${r.created}`),
    '', `## Queued (${queued.length})`, '', ...queued.map((r, i) => `- ${i + 1}. ${tag(r)} queued ${r.created}${r.data.not_before ? ` not_before ${r.data.not_before}` : ''}${trig(r)}${r.data.inputs?.length ? '; inputs ' + r.data.inputs.join(', ') : ''}${pe(r) ? '; ' + pe(r) : ''}${words(r)}`),
    '', `## Recent ends (${ends.length})`, '', ...ends.map(r => `- ${tag(r)} ${endWord(r)} ${r.updated}`)].join('\n') + '\n';
}

const RENDER = { questions: renderQuestions, decisions: renderDecisions, directives: renderDirectives, queue: renderQueue };
export const sha = s => crypto.createHash('sha256').update(s).digest('hex');
/** the key of a file in a hash file (the drive letter upper-cased): one launcher passes `c:\...` where another passes `C:\...` - two keys
 * for one file made each writer refuse the other's text as a "hand edit" (views frozen, a false Inbox notice) */
export const hashKey = f => { const p = path.resolve(f); return /^[a-z]:/.test(p) ? p[0].toUpperCase() + p.slice(1) : p; };

// VIEW-RACE: several processes write one view at once (every supervisor's fill, the tick, `norn status`, the dash server). Unlocked, a
// writer that read the hashes before another wrote the view took that writer's text for a hand edit (a lost update on the hash file did
// the same): META-QUEUE.md froze under a false Inbox notice. So (1) one lock per hash file (<hash file>.lock, O_EXCL, broken when stale),
// held from reading the hashes to renaming the hash file, in every guarded writer; (2) Norn keeps the last RECENT hashes it wrote per
// file (<hash file minus .json>.recent.json): a file whose text is any of them is Norn's own text - an older render, rewritten at once
// with a line in views/reclaimed.jsonl, never refused. Only text Norn never wrote (header gone, or a body no recent render had) is refused.
export const RECENT = 20;
const LOCK_STALE_MS = 10000;   // a holder renders and writes a few files: 10 s is a crashed holder, never a slow one
const TRANSIENT = ['EPERM', 'EACCES', 'EBUSY'];   // Windows: a file open in another process, or a delete pending
export const recentFile = hashFile => hashFile.replace(/\.json$/, '') + '.recent.json';
const sleepSync = ms => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
const sleep = ms => new Promise(r => setTimeout(r, ms));
const jsonOr = (t, d) => { try { return JSON.parse(t); } catch { return d; } };
const lockBody = token => JSON.stringify({ pid: process.pid, token, ts: new Date().toISOString() });
// a lock older than LOCK_STALE_MS (its ts, else its mtime while its JSON is not written yet); a gone lock counts as stale: the create is retried
const isStale = (raw, mtime) => { if (raw === null) return true; const ts = Date.parse(jsonOr(raw, {}).ts); return Date.now() - (Number.isNaN(ts) ? mtime : ts) > LOCK_STALE_MS; };
const retrySync = fn => { const t0 = Date.now(); for (;;) { try { return fn(); } catch (e) { if (!TRANSIENT.includes(e.code) || Date.now() - t0 > LOCK_STALE_MS) throw e; sleepSync(10); } } };
const retryAsync = async fn => { const t0 = Date.now(); for (;;) { try { return await fn(); } catch (e) { if (!TRANSIENT.includes(e.code) || Date.now() - t0 > LOCK_STALE_MS) throw e; await sleep(10); } } };
const readSync = f => { try { return fs.readFileSync(f, 'utf8'); } catch (e) { if (e.code === 'ENOENT') return null; throw e; } };
const readAsync = async f => { try { return await fs.promises.readFile(f, 'utf8'); } catch (e) { if (e.code === 'ENOENT') return null; throw e; } };

/** take <hashFile>.lock (waits while a live holder has it) -> release() */
export function lockHashesSync(hashFile) {
  const lf = hashFile + '.lock', token = `${process.pid}-${crypto.randomBytes(6).toString('hex')}`;
  fs.mkdirSync(path.dirname(lf), { recursive: true });
  for (;;) {
    try { fs.writeFileSync(lf, lockBody(token), { flag: 'wx' }); break; } catch (e) { if (e.code !== 'EEXIST' && !TRANSIENT.includes(e.code)) throw e; }
    let raw = null, mtime = Date.now();
    try { raw = fs.readFileSync(lf, 'utf8'); mtime = fs.statSync(lf).mtimeMs; } catch (e) { if (e.code !== 'ENOENT') { sleepSync(5); continue; } }
    if (isStale(raw, mtime)) { try { fs.unlinkSync(lf); } catch { /* gone, or another breaker: the next create says */ } } else sleepSync(2 + Math.random() * 8);
  }
  return () => retrySync(() => { try { if (jsonOr(fs.readFileSync(lf, 'utf8'), {}).token === token) fs.unlinkSync(lf); } catch (e) { if (e.code !== 'ENOENT') throw e; } });
}
/** lockHashesSync on fs.promises (the dash server's path) -> async release() */
export async function lockHashes(hashFile) {
  const fp = fs.promises, lf = hashFile + '.lock', token = `${process.pid}-${crypto.randomBytes(6).toString('hex')}`;
  await fp.mkdir(path.dirname(lf), { recursive: true });
  for (;;) {
    try { await fp.writeFile(lf, lockBody(token), { flag: 'wx' }); break; } catch (e) { if (e.code !== 'EEXIST' && !TRANSIENT.includes(e.code)) throw e; }
    let raw = null, mtime = Date.now();
    try { raw = await fp.readFile(lf, 'utf8'); mtime = (await fp.stat(lf)).mtimeMs; } catch (e) { if (e.code !== 'ENOENT') { await sleep(5); continue; } }
    if (isStale(raw, mtime)) { try { await fp.unlink(lf); } catch { /* gone, or another breaker */ } } else await sleep(2 + Math.random() * 8);
  }
  return () => retryAsync(async () => { try { if (jsonOr(await fp.readFile(lf, 'utf8'), {}).token === token) await fp.unlink(lf); } catch (e) { if (e.code !== 'ENOENT') throw e; } });
}

// one file's fate, read under the lock: no file / Norn's last text -> write; the same text -> unchanged; an older Norn text -> reclaim; else refused
const verdict = (cur, text, key, H, R) => cur === null ? 'write' : cur === text ? 'unchanged' : H[key] === sha(cur) ? 'write'
  : (R[key] || []).includes(sha(cur)) ? 'reclaim' : 'refused';
const remember = (H, R, key, s) => { H[key] = s; R[key] = [s, ...(R[key] || []).filter(x => x !== s)].slice(0, RECENT); };
const reclaimLine = (p, cur) => JSON.stringify({ ts: new Date().toISOString(), file: hashKey(p), sha: sha(cur), pid: process.pid, why: 'an older Norn render: rewritten' }) + '\n';

/** the guard: each job { file, text: () => string } (rendered under the lock: the last writer writes the newest state) -> Map(abs path -> written | unchanged | refused) */
function guardSync(hashFile, jobs) {
  const release = lockHashesSync(hashFile), rf = recentFile(hashFile), out = new Map();
  try {
    const h0 = readSync(hashFile), r0 = readSync(rf), H = h0 === null ? {} : JSON.parse(h0), R = r0 === null ? {} : JSON.parse(r0);
    for (const j of jobs) {
      const p = path.resolve(j.file), key = hashKey(p), text = j.text(), cur = readSync(p), v = verdict(cur, text, key, H, R);
      if (v === 'refused') { out.set(p, v); continue; }
      if (v !== 'unchanged') { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(`${p}.${process.pid}.tmp`, text); retrySync(() => fs.renameSync(`${p}.${process.pid}.tmp`, p)); }
      if (v === 'reclaim') fs.appendFileSync(path.join(path.dirname(hashFile), 'reclaimed.jsonl'), reclaimLine(p, cur));
      remember(H, R, key, sha(text));
      out.set(p, v === 'unchanged' ? v : 'written');
    }
    for (const [f, old, v] of [[hashFile, h0, H], [rf, r0, R]]) {
      const t = JSON.stringify(v, null, 1) + '\n';
      if (t !== old) { fs.writeFileSync(`${f}.${process.pid}.tmp`, t); retrySync(() => fs.renameSync(`${f}.${process.pid}.tmp`, f)); }
    }
  } finally { release(); }
  return out;
}
async function guardAsync(hashFile, jobs) {
  const fp = fs.promises, release = await lockHashes(hashFile), rf = recentFile(hashFile), out = new Map();
  try {
    const h0 = await readAsync(hashFile), r0 = await readAsync(rf), H = h0 === null ? {} : JSON.parse(h0), R = r0 === null ? {} : JSON.parse(r0);
    for (const j of jobs) {
      const p = path.resolve(j.file), key = hashKey(p), text = j.text(), cur = await readAsync(p), v = verdict(cur, text, key, H, R);
      if (v === 'refused') { out.set(p, v); continue; }
      if (v !== 'unchanged') { await fp.mkdir(path.dirname(p), { recursive: true }); await fp.writeFile(`${p}.${process.pid}.tmp`, text); await retryAsync(() => fp.rename(`${p}.${process.pid}.tmp`, p)); }
      if (v === 'reclaim') await fp.appendFile(path.join(path.dirname(hashFile), 'reclaimed.jsonl'), reclaimLine(p, cur));
      remember(H, R, key, sha(text));
      out.set(p, v === 'unchanged' ? v : 'written');
    }
    for (const [f, old, v] of [[hashFile, h0, H], [rf, r0, R]]) {
      const t = JSON.stringify(v, null, 1) + '\n';
      if (t !== old) { await fp.writeFile(`${f}.${process.pid}.tmp`, t); await retryAsync(() => fp.rename(`${f}.${process.pid}.tmp`, f)); }
    }
  } finally { await release(); }
  return out;
}
const tally = m => { const res = { written: [], unchanged: [], refused: [] }; for (const [p, v] of m) res[v].push(p); return res; };

// the records views (or only the queue view) as guard jobs + their hash file; the queue view reads the records itself, under the lock
function viewJobs(stateDir, st, paths, only, ready) {
  const queue = only?.length === 1 && only[0] === 'queue', vdir = path.join(stateDir, 'views');
  const evalAfter = makeEval(stateDir);   // lazy: reads records only when a queued run has after: conditions
  const jobs = Object.entries(RENDER).filter(([name]) => (only ? only.includes(name) : name !== 'queue')).map(([name, render]) => ({
    file: path.resolve(paths[name] || path.join(queue ? stateDir : vdir, VIEW_FILES[name])),   // the queue view sits beside DIGEST.md
    text: () => render(queue ? loadState(stateDir) : st, { evalAfter, ready }) }));
  return { hashFile: path.join(vdir, queue ? 'queue-hashes.json' : 'hashes.json'), jobs };
}

/** Write the views; paths default to <stateDir>/views/<VIEW_FILES>. Returns { written, unchanged, refused } (absolute paths).
 * NORN-WATCH S4: the queue view is written only by writeQueueView (fillQueue and `meta views`), with its own hash file. */
export function writeViews(stateDir, st, paths = {}, { only = null, ready = null } = {}) {
  const { hashFile, jobs } = viewJobs(stateDir, st, paths, only, ready);
  return tally(guardSync(hashFile, jobs));
}

/** META-DASH-ASYNC R1 (option a): writeViews on fs.promises - the dash server's write path (a sync write blocks the event loop the
 * page and its streams run on). The same views, hashes, lock and hand-edit guard as writeViews; the CLI keeps the sync form. */
export async function writeViewsAsync(stateDir, st, paths = {}, { only = null, ready = null } = {}) {
  const { hashFile, jobs } = viewJobs(stateDir, st, paths, only, ready);
  return tally(await guardAsync(hashFile, jobs));
}

/** META-ROADMAP S1: (re)write ONE generated file under the same hand-edit guard, its hashes in their own file -> written | unchanged | refused */
export const writeGuarded = (hashFile, file, text) => guardSync(hashFile, [{ file, text: () => text }]).get(path.resolve(file));
/** META-DASH-ASYNC R1 (option a): writeGuarded on fs.promises for the dash server (the same guard, lock and hashes); the CLI keeps the sync form */
export const writeGuardedAsync = async (hashFile, file, text) => (await guardAsync(hashFile, [{ file, text: () => text }])).get(path.resolve(file));

/** NORN-WATCH S4: (re)write <stateDir>/META-QUEUE.md (or paths.queue) from the records; refuses a hand edit like every view. */
export const writeQueueView = (stateDir, paths = {}, { ready = null } = {}) => writeViews(stateDir, null, paths, { only: ['queue'], ready });

// NORN-WATCH S1: the resume digest (digest.mjs) as markdown - `norn digest`, STATUS.md's `## Digest` block, <state>/DIGEST.md.
// level = `##` (DIGEST.md) or `###` (inside STATUS.md); rows carry their ids so a resumed session can act on each.
export function renderDigest(d, { level = 2 } = {}) {
  const h = '#'.repeat(level), s = d.sections;
  const L = [`${h} Digest ${d.project ? d.project + ' ' : ''}${d.at.slice(0, 16)}Z (level-triggered: a row leaves only when its target state is reached)`];
  const sec = (title, rows, line) => { L.push(`${h}# ${title} (${rows.length})`); L.push(...(rows.length ? rows.map(line) : ['- (none)'])); };
  // META-CONTROLLER C4: first, while any lane is held - the check-in skips these lanes this tick (no write; its writes there exit 5)
  if (s.held) sec('0 HELD (skip): the controller works on these lanes', s.held, r => `- ${r.id} HELD (skip) by ${r.who} until ${String(r.until).slice(11, 16)}Z (${r.min} min)`
    + `${r.why ? ': ' + r.why : ''}`);
  // GAP-1: first, while ALL queued work waits on one machine-level hold - no check-in clears it: report it, the owner has the Inbox item
  if (s.hold) sec('0b EVERYTHING HELD (report it; only the owner clears it)', s.hold, r => `- HOLD ${r.runs.length} queued${r.scope === 'claude' ? ' Claude' : ''} run(s)`
    + `${r.merges ? ` incl. ${r.merges} merge(s)` : ''} held since ${r.since} (${r.min} min) on "${r.term}": ${r.reason}; fix: ${r.fix}${r.clears ? `; or it clears ${r.clears}` : ''}`);
  sec('1 Finished, not on main', s.finished, r => r.kind === 'deliverable'
    ? `- ${r.id} ${r.lane ?? '-'} ${r.branch ?? '-'} ${r.why}${r.days !== null ? ` ${r.days} d` : ''}${r.run ? ` (${r.run})` : ''}: ${String(r.what).slice(0, 120)}`
    : `- ${r.id} ${r.lane ?? '-'}${r.stage ? ' ' + r.stage : ''} ${r.branch ?? '?'} ${r.why}; review ${r.review}; ended ${r.ended} (${r.hours} h)`);
  sec('2 Queued + triggers', s.queued, r => `- ${r.id} ${r.lane ?? '-'}${r.stage ? ' ' + r.stage : ''} not_before ${r.not_before ?? '-'}`
    + `${r.after.length ? '; after ' + r.after.map(a => `${a.cond}=${a.met === null ? '?' : a.met ? 'met' : a.gone ? 'gone' : 'unmet'}`).join(', ') : ''}`
    + `${r.inputs.length ? '; inputs ' + r.inputs.join(', ') : ''}${r.terms ? '; ' + readyWords(r) : ''}`);
  sec('3 Questions', s.questions, r => `- ${r.id} ${r.state}${r.owner_only ? ' OWNER-ONLY' : ''} ${r.lane ?? '-'} (${r.hours} h): ${r.title}`
    + (r.answered_by ? `
  - ${r.id} open, possibly answered by ${r.answered_by} (${r.answered_why}): close it with META rec answer ${r.id} --from ${r.answered_by}, or META rec not-an-answer ${r.answered_by} --q ${r.id}` : ''));
  sec('4 Ended without a clean successor', s.ended, r => `- ${r.id} ${r.lane ?? '-'}${r.stage ? ' ' + r.stage : ''} ${r.state} ${r.outcome} exit=${r.exit ?? '-'}`
    + `${r.dirty !== null ? ` dirty=${r.dirty}` : ''}${r.external_term ? ' external_term' : ''} ended ${r.ended} (${r.hours} h)${r.worktree ? ' wt ' + r.worktree : ''}`);
  sec('5 Directives with no action', s.directives, r => `- ${r.id} (${r.hours} h): ${r.text}`);
  if (s.ci) sec('6 CI red on main', s.ci, r => `- ${r.id} ${r.repo} run ${r.run} ${String(r.sha ?? '-').slice(0, 9)} ${r.conclusion} created ${r.created} (${r.hours} h); failing: `
    + `${r.failing === null ? 'not read yet' : r.failing.length ? r.failing.slice(0, 8).join('; ') : 'none named in the log'}; fix task: queue a lane, never a re-run`);
  // META-ROADMAP S3: the audit's Unplaced list (only once the project has a roadmap); place each with norn road add --from / link
  if (s.roadmap) sec('7 Unplaced on the roadmap', s.roadmap, r => `- ${r.id} ${r.kind}: ${r.why}`);
  // META-GUARD R1: open usage alarms; the check-in rules each (let it run / mail it / stop it), Norn never kills a run by itself
  if (s.guard) sec('8 Usage guard', s.guard, r => (r.kind === 'drift' ? `- ${r.run} drift` : `- ${r.id} ${r.run} ${r.cls}`) + `${r.lane ? ' ' + r.lane : ''}: ${r.why}`);
  if (s.slop) sec('9 SloppaChoppa', s.slop, r => '- ' + r.line);
  if (s.advice) sec('10 Model advice', s.advice, r => '- ' + r.line);   // META-TEND P4: one tap on the Inbox card applies or keeps each
  // META-DOD 3: read the findings, then review the review run (it releases the build it holds) or withdraw / requeue the build
  if (s.critique) sec('11 Plan reviews to read', s.critique, r => `- ${r.id} review of ${r.of} (${r.plan}): ${r.outcome === 'done' ? '' : r.outcome + ', '}${r.findings ?? '?'} finding${r.findings === 1 ? '' : 's'} in ${r.file}; holds ${r.holds.length ? r.holds.join(', ') : 'no queued run'}`);
  // gap #5: one active directive restating another; the check-in folds the pair (CHECKIN.md 2b), the row leaves when one is not active
  if (s.dupdirs) sec('12 Possible duplicate directives', s.dupdirs, r => `- possible duplicate directives: ${r.older} ~ ${r.newer} (${r.why}): fold them, `
    + `e.g. META rec supersede ${r.older} --by ${r.newer} --why "restated by ${r.newer}"`);
  return L.join('\n') + '\n';
}
