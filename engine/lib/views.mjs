/** NORN-WATCH S4: (re)write <stateDir>/META-QUEUE.md (or paths.queue) from the records; refuses a hand edit like every view. */
export const writeQueueView = (stateDir, paths = {}, { ready = null } = {}) => writeViews(stateDir, null, paths, { only: ['queue'], ready });

// NORN-WATCH S1: the resume digest (digest.mjs) as markdown - `norn digest`, STATUS.md's `## Digest` block, <state>/DIGEST.md.
// level = `##` (DIGEST.md) or `###` (inside STATUS.md); rows carry their ids so a resumed session can act on each.
export function renderDigest(d, { level = 2 } = {}) {
  const h = '#'.repeat(level), s = d.sections;
  const L = [`${h} Digest ${d.project ? d.project + ' ' : ''}${d.at.slice(0, 16)}Z (level-triggered: a row leaves only when its target state is reached)`];
  const sec = (title, rows, line) => { L.push(`${h}# ${title} (${rows.length})`); L.push(...(rows.length ? rows.map(line) : ['- (none)'])); };
  // META-CONTROLLER C4: first, while any lane is held - the check-in skips these lanes this tick (no write; its writes there exit 5)
  if (s.held) sec('0 HELD (skip): the controller works on these lanes', s.held, r => `- ${r.id} HELD (skip) by ${r.who} until ${String(r.until).slice(11, 16)}Z (${r.min} min)`
    + `${r.why ? ': ' + r.why : ''}`);
  // GAP-1: first, while ALL queued work waits on one machine-level hold - no check-in clears it: report it, the owner has the Inbox item
  if (s.hold) sec('0b EVERYTHING HELD (report it; only the owner clears it)', s.hold, r => `- HOLD ${r.runs.length} queued${r.scope === 'claude' ? ' Claude' : ''} run(s)`
    + `${r.merges ? ` incl. ${r.merges} merge(s)` : ''} held since ${r.since} (${r.min} min) on "${r.term}": ${r.reason}; fix: ${r.fix}${r.clears ? `; or it clears ${r.clears}` : ''}`);
  sec('1 Finished, not on main', s.finished, r => r.kind === 'deliverable'
    ? `- ${r.id} ${r.lane ?? '-'} ${r.branch ?? '-'} ${r.why}${r.days !== null ? ` ${r.days} d` : ''}${r.run ? ` (${r.run})` : ''}: ${String(r.what).slice(0, 120)}`
    : `- ${r.id} ${r.lane ?? '-'}${r.stage ? ' ' + r.stage : ''} ${r.branch ?? '?'} ${r.why}; review ${r.review}; ended ${r.ended} (${r.hours} h)`);
  sec('2 Queued + triggers', s.queued, r => `- ${r.id} ${r.lane ?? '-'}${r.stage ? ' ' + r.stage : ''} not_before ${r.not_before ?? '-'}`
    + `${r.after.length ? '; after ' + r.after.map(a => `${a.cond}=${a.met === null ? '?' : a.met ? 'met' : a.gone ? 'gone' : 'unmet'}`).join(', ') : ''}`
    + `${r.inputs.length ? '; inputs ' + r.inputs.join(', ') : ''}${r.terms ? '; ' + readyWords(r) : ''}`);
  sec('3 Questions', s.questions, r => `- ${r.id} ${r.state}${r.owner_only ? ' OWNER-ONLY' : ''} ${r.lane ?? '-'} (${r.hours} h): ${r.title}`
    + (r.answered_by ? `
  - ${r.id} open, possibly answered by ${r.answered_by} (${r.answered_why}): close it with META rec answer ${r.id} --from ${r.answered_by}, or META rec not-an-answer ${r.answered_by} --q ${r.id}` : ''));
  sec('4 Ended without a clean successor', s.ended, r => `- ${r.id} ${r.lane ?? '-'}${r.stage ? ' ' + r.stage : ''} ${r.state} ${r.outcome} exit=${r.exit ?? '-'}`
    + `${r.dirty !== null ? ` dirty=${r.dirty}` : ''}${r.external_term ? ' external_term' : ''} ended ${r.ended} (${r.hours} h)${r.worktree ? ' wt ' + r.worktree : ''}`);
  sec('5 Directives with no action', s.directives, r => `- ${r.id} (${r.hours} h): ${r.text}`);
  if (s.ci) sec('6 CI red on main', s.ci, r => `- ${r.id} ${r.repo} run ${r.run} ${String(r.sha ?? '-').slice(0, 9)} ${r.conclusion} created ${r.created} (${r.hours} h); failing: `
    + `${r.failing === null ? 'not read yet' : r.failing.length ? r.failing.slice(0, 8).join('; ') : 'none named in the log'}; fix task: queue a lane, never a re-run`);
  // META-ROADMAP S3: the audit's Unplaced list (only once the project has a roadmap); place each with norn road add --from / link
  if (s.roadmap) sec('7 Unplaced on the roadmap', s.roadmap, r => `- ${r.id} ${r.kind}: ${r.why}`);
  // META-GUARD R1: open usage alarms; the check-in rules each (let it run / mail it / stop it), Norn never kills a run by itself
  if (s.guard) sec('8 Usage guard', s.guard, r => (r.kind === 'drift' ? `- ${r.run} drift` : `- ${r.id} ${r.run} ${r.cls}`) + `${r.lane ? ' ' + r.lane : ''}: ${r.why}`);
  if (s.slop) sec('9 SloppaChoppa', s.slop, r => '- ' + r.line);
  if (s.advice) sec('10 Model advice', s.advice, r => '- ' + r.line);   // META-TEND P4: one tap on the Inbox card applies or keeps each
  // META-DOD 3: read the findings, then review the review run (it releases the build it holds) or withdraw / requeue the build
  if (s.critique) sec('11 Plan reviews to read', s.critique, r => `- ${r.id} review of ${r.of} (${r.plan}): ${r.outcome === 'done' ? '' : r.outcome + ', '}${r.findings ?? '?'} finding${r.findings === 1 ? '' : 's'} in ${r.file}; holds ${r.holds.length ? r.holds.join(', ') : 'no queued run'}`);
  // gap #5: one active directive restating another; the check-in folds the pair (CHECKIN.md 2b), the row leaves when one is not active
  if (s.dupdirs) sec('12 Possible duplicate directives', s.dupdirs, r => `- possible duplicate directives: ${r.older} ~ ${r.newer} (${r.why}): fold them, `
    + `e.g. META rec supersede ${r.older} --by ${r.newer} --why "restated by ${r.newer}"`);
  return L.join('\n') + '\n';
}
