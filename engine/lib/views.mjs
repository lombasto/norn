const ofKind = (st, kind) => Object.values(st.items).filter(i => i.kind === kind).sort((a, b) => num(a.id) - num(b.id));
const cell = v => (v === undefined || v === null ? '' : Array.isArray(v) ? v.join(', ') : String(v)).replace(/\|/g, '\\|').replace(/\r?\n/g, '<br>');
const who = it => (it.by === 'migration' && it.data?.legacy_by ? `${it.data.legacy_by} (migrated)` : it.by) +(it.run ? ` (${it.run})` : '');

function closedLine(q) {
  if (q.state === 'applied') return `applied ${q.apply.refs.join(', ')} (${q.updated})`;
  if (q.state === 'superseded') return `superseded by ${q.supersede.by}: ${q.supersede.why} (${q.updated})`;
  if (q.state === 'withdrawn') return `withdrawn${q.withdraw.why ? ': ' + q.withdraw.why : ''} (${q.updated})`;
  return q.state;
}

function questionBlock(q) {
  const d = q.data;
  const meta = [`lane ${d.lane}`, d.class ? `class ${d.class}` : null, d.blocks?.length ? `blocks ${d.blocks.join(', ')}` : null,
    `asked ${q.created} by ${who(q)}`, d.source ? `source ${d.source}` : null, d.origin ? `options from ${d.origin.file}#${d.origin.section}` : null].filter(Boolean).join(' · ');
  const out = [`### ${q.id} · ${d.title}`, meta];
  if (d.body) out.push('', d.body);
  if (d.options?.length) { out.push('', 'Options:'); for (const o of d.options) out.push(`- **${o.key}** ${o.text}${o.cost ? ` (cost: ${o.cost})` : ''}${o.added_by ? ` (added by ${o.added_by})` : ''}`); }
  if (d.recommend) out.push('', `Recommended: **${d.recommend.key}**${d.recommend.from ? ` (${d.recommend.from === 'source' ? 'plan default' : d.recommend.from})` : ''} - ${d.recommend.why}`);
  const th = q.history.some(h => h.ev === 'say' || h.ev === 'reply') ? threadLines(q) : [];   // INBOX-REPLIES: the owner's messages and the controller's replies
  if (th.length) out.push('', 'Thread:', ...th);
  if (q.state === 'answered') out.push('', `Answer (${q.answer.via}, ${q.history.findLast(h => h.ev === 'answer').ts}): ${q.answer.choice ? `**${q.answer.choice}** - ` : ''}"${q.answer.text}"`);
  return out.join('\n');
}

export function renderQuestions(st) {
  const qs = ofKind(st, 'question');
  const open = qs.filter(q => q.state === 'open'), answered = qs.filter(q => q.state === 'answered');
  const closed = qs.filter(q => !['open', 'answered'].includes(q.state));
  const out = [HEADER, '# Owner questions', '', `## Open (${open.length})`];
  for (const q of open) out.push('', questionBlock(q));
  out.push('', `## Answered, not applied (${answered.length})`);
  for (const q of answered) out.push('', questionBlock(q));
  out.push('', `## Closed (${closed.length})`, '');
  for (const q of closed) out.push(`- ${q.id} · ${q.data.title} - ${closedLine(q)}`);
  return out.join('\n') + '\n';
}

export function renderDecisions(st) {
  const out = [HEADER, '# Decisions log', '', '| id | state | date | lane | question | choice | why | cost | source | by | answers | notify |',
    '|---|---|---|---|---|---|---|---|---|---|---|---|'];
  for (const d of ofKind(st, 'decision')) {
    const x = d.data;
    const state = d.state === 'superseded' ? `superseded by ${d.supersede.by}: ${d.supersede.why}`
      : d.state === 'overruled' ? `overruled: ${d.overrule.text}${d.overrule.rework_lane ? ` (rework ${d.overrule.rework_lane})` : ''}` : d.state;
    out.push('| ' + [d.id, state, d.created, x.lane, x.question, x.choice, x.why, x.cost, x.source, who(d), x.answers, x.notify ? 'FYI' : ''].map(cell).join(' | ') + ' |');
  }
  return out.join('\n') + '\n';
}

export function renderDirectives(st) {
  const ds = ofKind(st, 'directive');
  const line = d => {
    const x = d.data;
    const tags = [d.created, x.via, x.scope?.length ? `scope ${x.scope.join(', ')}` : null, x.expires_utc ? `expires ${x.expires_utc}` : null].filter(Boolean).join(', ');
    const end = d.state === 'superseded' ? ` - superseded${d.supersede.by ? ` by ${d.supersede.by}` : ''}: ${d.supersede.why}`
      : d.state === 'done' ? ` - done ${d.done.refs.join(', ')}` : d.state === 'revoked' ? ' - revoked' : '';
    return `- ${d.id} (${tags}): ${x.text.replace(/\r?\n/g, ' ')}${end}`;
  };
  const active = ds.filter(d => d.state === 'active'), closed = ds.filter(d => d.state !== 'active');
  return [HEADER, '# Active owner directives (add / revoke in the dashboard; full history: norn rec list --kind DIR)', '', `## Active (${active.length})`, '', ...active.map(line), '', `## Closed (${closed.length})`, '', ...closed.map(line)].join('\n') + '\n';
}

// NORN-WATCH S4: META-QUEUE.md as a generated view - running / queued (+ each after: condition, inputs) / the last 10 ends.
// evalAfter (after.mjs makeEval) evaluates the triggers; without it a condition shows `?`. No clock in the text: one state = one text.
// META-GTP-DAG piece 3: ready = the dry fill walk's rows (runs.mjs readiness); each queued row ends with its words (readyWords) and the
// rows follow the fill order. Without them (a caller with no walk) the order is FIFO and no words are printed.
export function renderQueue(st, { evalAfter = null, ready = null } = {}) {
  const runs = ofKind(st, 'run');
  const tag = r => [r.id, r.data.dwarf ? `dwarf ${r.data.dwarf}` : null, r.data.lane ? `lane ${r.data.lane}` : null, r.data.stage, r.data.executor, r.data.model !== r.data.executor && r.data.model].filter(Boolean).join(' ');   // the fake's model is 'fake': said once
  const running = runs.filter(r => r.state === 'running');
  const R = ready ? new Map(ready.map((r, i) => [r.id, { ...r, order: i }])) : null;
  const queued = runs.filter(r => r.state === 'queued').sort((a, b) => (R ? (R.get(a.id)?.order ?? 1e9) - (R.get(b.id)?.order ?? 1e9) : 0));
  const words = r => { const x = R?.get(r.id); return x ? '; ' + readyWords(x) : ''; };
  const pe = r => [r.data.priority, r.data.epic].filter(Boolean).join(' ');
  const ends = runs.filter(r => ['exited', 'lost', 'killed', 'withdrawn'].includes(r.state)).sort((a, b) => Date.parse(b.updated) - Date.parse(a.updated) || num(b.id) - num(a.id)).slice(0, 10);
  const trig = r => {
    const after = r.data.after || [];
    if (!after.length) return '';
    const word = c => (c.met ? 'met' : c.gone ? `GONE (${c.gone})` : 'unmet');
    const a = evalAfter ? evalAll(after, evalAfter).conds : after.map(c => ({ cond: `${c.kind}:${c.id}:${c.state}`, met: null }));
    return '; after ' + a.map(c => `${c.cond} ${c.met === null ? '?' : word(c)}`).join(', ');
  };
  const endWord = r => r.state === 'exited' ? `ended ${r.end?.outcome ?? '?'}` : r.state === 'withdrawn' ? `withdrawn${r.withdraw?.why ? ': ' + r.withdraw.why : ''}` : r.state;
  return [HEADER, '# Queue - running, queued (with the trigger that releases each), recent ends',
    '', '(Prose next actions live in the ledger + DEC records; queue a triggered run with `norn run ... --after <conds> --inputs DLV-n`.)',
    '', `## Running (${running.length})`, '', ...running.map(r => `- ${tag(r)} since ${r.created}`),
    '', `## Queued (${queued.length})`, '', ...queued.map((r, i) => `- ${i + 1}. ${tag(r)} queued ${r.created}${r.data.not_before ? ` not_before ${r.data.not_before}` : ''}${trig(r)}${r.data.inputs?.length ? '; inputs ' + r.data.inputs.join(', ') : ''}${pe(r) ? '; ' + pe(r) : ''}${words(r)}`),
    '', `## Recent ends (${ends.length})`, '', ...ends.map(r => `- ${tag(r)} ${endWord(r)} ${r.updated}`)].join('\n') + '\n';
}

